    public static function all(): array
    {
        return self::E;
    }

    public static function get(string $k): ?array
    {
        return self::E[$k] ?? null;
    }

    /** نام متغیرها (لاتین) برای ippanel */
    public static function vars(string $k): array
    {
        return array_keys(self::E[$k][3] ?? []);
    }

    public static function template(string $k): string
    {
        return self::E[$k][4] ?? '%title% %body% %link%';
    }

    /** متن کامل پیامک با مقادیر (برای گزارش و ارسال عادی) */
    public static function render(string $k, array $vars): string
    {
        return preg_replace_callback('/%(\w+)%/', fn ($m) => (string) ($vars[$m[1]] ?? ''), self::template($k));
    }

    public static function patternCode(string $k): string
    {
        return trim((string) setting('sms_pat_'.$k));
    }
