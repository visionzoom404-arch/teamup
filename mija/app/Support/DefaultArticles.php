    public static function body(string $slug): string
    {
        $f = __DIR__.'/articles/'.$slug.'.html';

        return is_file($f) ? (string) file_get_contents($f) : '';
    }

    /** مقاله‌های پیش‌فرض را (فقط اگر slug وجود نداشت) می‌سازد */
    public static function seed(): void
    {
        foreach (self::LIST as $slug => [$title, $metaTitle, $excerpt, $kw, $cat, $alt, $ago]) {
            if (Article::where('slug', $slug)->exists() || ! ($body = self::body($slug))) {
                continue;
            }
            Article::create([
                'slug' => $slug, 'title' => $title, 'meta_title' => $metaTitle, 'excerpt' => $excerpt, 'keyword' => $kw, 'category' => $cat,
                'body' => $body, 'image' => 'img/blog/'.$slug.'.jpg', 'image_alt' => $alt, 'status' => 'published', 'published_at' => now()->subDays($ago),
            ]);
        }
    }
